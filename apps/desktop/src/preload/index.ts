import { contextBridge, ipcRenderer } from 'electron';
import {
  AUTH_CHANGE_PASSWORD_CHANNEL,
  AUTH_LOGIN_CHANNEL,
  AUTH_LOGOUT_CHANNEL,
  AUTH_SESSION_CHANNEL,
  AREAS_CREATE_CHANNEL,
  AREAS_STATUS_CHANNEL,
  AREAS_UPDATE_CHANNEL,
  COLLECTION_REFERENCES_LIST_CHANNEL,
  COLLECTORS_CREATE_CHANNEL,
  COLLECTORS_STATUS_CHANNEL,
  COLLECTORS_UPDATE_CHANNEL,
  REFERENCE_DATA_CHANNEL,
  PLANS_CREATE_CHANNEL,
  PLANS_LIST_CHANNEL,
  PLANS_STATUS_CHANNEL,
  PLANS_UPDATE_CHANNEL,
  SERVICES_CREATE_CHANNEL,
  SERVICES_STATUS_CHANNEL,
  SERVICES_UPDATE_CHANNEL,
  SUBSCRIBERS_CREATE_CHANNEL,
  SUBSCRIBERS_AUDIT_CHANNEL,
  SUBSCRIBERS_FINANCIAL_CHANNEL,
  SUBSCRIBERS_STATUS_CHANNEL,
  SUBSCRIBERS_UPDATE_CHANNEL,
  SUBSCRIBERS_GET_CHANNEL,
  SUBSCRIBERS_LIST_CHANNEL,
  type DesktopBridge,
  DASHBOARD_GET_CHANNEL, REPORT_GET_CHANNEL, REPORT_EXPORT_CHANNEL, SERVICE_HISTORY_CHANNEL,
} from '@bcis/shared';

// No ipcRenderer, generic channel, URL, or arbitrary arguments cross this boundary.
const bridge: DesktopBridge = Object.freeze({
  getConnection: () => ipcRenderer.invoke('bcis:connection:get'),
  getSession: () => ipcRenderer.invoke(AUTH_SESSION_CHANNEL),
  login: (input: Parameters<DesktopBridge['login']>[0]) => ipcRenderer.invoke(AUTH_LOGIN_CHANNEL, input),
  changePassword: (input: Parameters<DesktopBridge['changePassword']>[0]) => ipcRenderer.invoke(AUTH_CHANGE_PASSWORD_CHANNEL, input),
  logout: () => ipcRenderer.invoke(AUTH_LOGOUT_CHANNEL),
  listSubscribers: (query: Parameters<DesktopBridge['listSubscribers']>[0]) => ipcRenderer.invoke(SUBSCRIBERS_LIST_CHANNEL, query),
  getSubscriber: (id: string) => ipcRenderer.invoke(SUBSCRIBERS_GET_CHANNEL, id),
  createSubscriber: (input: Parameters<DesktopBridge['createSubscriber']>[0]) => ipcRenderer.invoke(SUBSCRIBERS_CREATE_CHANNEL, input),
  updateSubscriber: (id: string, input: Parameters<DesktopBridge['updateSubscriber']>[1]) => ipcRenderer.invoke(SUBSCRIBERS_UPDATE_CHANNEL, { id, input }),
  changeSubscriberStatus: (id: string, input: Parameters<DesktopBridge['changeSubscriberStatus']>[1]) => ipcRenderer.invoke(SUBSCRIBERS_STATUS_CHANNEL, { id, input }),
  getSubscriberFinancialProfile: (id: string) => ipcRenderer.invoke(SUBSCRIBERS_FINANCIAL_CHANNEL, id),
  getSubscriberAudit: (id: string) => ipcRenderer.invoke(SUBSCRIBERS_AUDIT_CHANNEL, id),
  createServiceAccount: (subscriberId: string, input: Parameters<DesktopBridge['createServiceAccount']>[1]) => ipcRenderer.invoke(SERVICES_CREATE_CHANNEL, { subscriberId, input }),
  updateServiceAccount: (subscriberId: string, serviceId: string, input: Parameters<DesktopBridge['updateServiceAccount']>[2]) => ipcRenderer.invoke(SERVICES_UPDATE_CHANNEL, { subscriberId, serviceId, input }),
  changeServiceAccountStatus: (subscriberId: string, serviceId: string, input: Parameters<DesktopBridge['changeServiceAccountStatus']>[2]) => ipcRenderer.invoke(SERVICES_STATUS_CHANNEL, { subscriberId, serviceId, input }),
  getServicePlans: () => ipcRenderer.invoke(PLANS_LIST_CHANNEL),
  createServicePlan: (input: Parameters<DesktopBridge['createServicePlan']>[0]) => ipcRenderer.invoke(PLANS_CREATE_CHANNEL, input),
  updateServicePlan: (id: string, input: Parameters<DesktopBridge['updateServicePlan']>[1]) => ipcRenderer.invoke(PLANS_UPDATE_CHANNEL, { id, input }),
  changeServicePlanStatus: (id: string, input: Parameters<DesktopBridge['changeServicePlanStatus']>[1]) => ipcRenderer.invoke(PLANS_STATUS_CHANNEL, { id, input }),
  getCollectionReferences: () => ipcRenderer.invoke(COLLECTION_REFERENCES_LIST_CHANNEL),
  createCollectionArea: (input: Parameters<DesktopBridge['createCollectionArea']>[0]) => ipcRenderer.invoke(AREAS_CREATE_CHANNEL, input),
  updateCollectionArea: (id: string, input: Parameters<DesktopBridge['updateCollectionArea']>[1]) => ipcRenderer.invoke(AREAS_UPDATE_CHANNEL, { id, input }),
  changeCollectionAreaStatus: (id: string, input: Parameters<DesktopBridge['changeCollectionAreaStatus']>[1]) => ipcRenderer.invoke(AREAS_STATUS_CHANNEL, { id, input }),
  createCollector: (input: Parameters<DesktopBridge['createCollector']>[0]) => ipcRenderer.invoke(COLLECTORS_CREATE_CHANNEL, input),
  updateCollector: (id: string, input: Parameters<DesktopBridge['updateCollector']>[1]) => ipcRenderer.invoke(COLLECTORS_UPDATE_CHANNEL, { id, input }),
  changeCollectorStatus: (id: string, input: Parameters<DesktopBridge['changeCollectorStatus']>[1]) => ipcRenderer.invoke(COLLECTORS_STATUS_CHANNEL, { id, input }),
  getReferenceData: () => ipcRenderer.invoke(REFERENCE_DATA_CHANNEL),
  getDashboard: (query: Parameters<DesktopBridge['getDashboard']>[0]) => ipcRenderer.invoke(DASHBOARD_GET_CHANNEL, query),
  getReport: (query: Parameters<DesktopBridge['getReport']>[0]) => ipcRenderer.invoke(REPORT_GET_CHANNEL, query),
  exportReport: (input: Parameters<DesktopBridge['exportReport']>[0]) => ipcRenderer.invoke(REPORT_EXPORT_CHANNEL, input),
  getServiceHistory: (id: string) => ipcRenderer.invoke(SERVICE_HISTORY_CHANNEL, id),
});
contextBridge.exposeInMainWorld('bcis', bridge);
